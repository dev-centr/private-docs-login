#!/usr/bin/env node
// Builds src/assets.generated.mjs from assets/. The issuer serves these files from memory on both
// the Node host and the Worker, so no bundler rule or static-file host is needed.
// Run after changing anything in assets/: node scripts/build-assets.mjs (the test suite checks it is current).
import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const read = (path) => readFileSync(join(root, path))
const short = (bytes) => createHash("sha256").update(bytes).digest("hex").slice(0, 10)

export function buildAssets() {
  const font = read("assets/fonts/space-grotesk-latin-wght-normal.woff2")
  const fontPath = `/assets/space-grotesk-latin-wght.${short(font)}.woff2`
  const css = Buffer.from(read("assets/pages.css").toString("utf8").replaceAll("__FONT_URL__", fontPath), "utf8")
  const cssPath = `/assets/pages.${short(css)}.css`
  const glyph = read("assets/icons/private-docs-login-glyph.svg")
  const glyphPath = `/assets/private-docs-login-glyph.${short(glyph)}.svg`
  const mark = read("assets/icons/private-docs-login-mark.svg")
  const markPath = `/assets/private-docs-login-mark.${short(mark)}.svg`
  const files = [
    { path: fontPath, type: "font/woff2", bytes: font },
    { path: cssPath, type: "text/css; charset=utf-8", bytes: css },
    { path: glyphPath, type: "image/svg+xml", bytes: glyph },
    { path: markPath, type: "image/svg+xml", bytes: mark },
  ]
  const lines = [
    "// Generated by scripts/build-assets.mjs from assets/. Do not edit by hand.",
    `export const ASSET_URLS = ${JSON.stringify({ css: cssPath, font: fontPath, glyph: glyphPath, favicon: markPath }, null, 2)}`,
    "",
    "export const ASSET_FILES = {",
    ...files.map((file) => `  ${JSON.stringify(file.path)}: { type: ${JSON.stringify(file.type)}, base64: ${JSON.stringify(file.bytes.toString("base64"))} },`),
    "}",
    "",
  ]
  return lines.join("\n")
}

const isMain = Boolean(process.argv[1]) && resolve(fileURLToPath(import.meta.url)).toLowerCase() === resolve(process.argv[1]).toLowerCase()
if (isMain) {
  writeFileSync(join(root, "src", "assets.generated.mjs"), buildAssets())
  console.log("Wrote src/assets.generated.mjs")
}
